class KnowledgeDocument(Base):
    """
    A vulnerability document ingested from Awesome-POC or other source.
    Paper: "Awesome-POC provides abundant vulnerability example data."
    """
    __tablename__ = "knowledge_documents"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    source = Column(String(100), nullable=False)           # awesome-poc, nvd, custom
    source_path = Column(String(500), nullable=True)       # File path in repo
    title = Column(String(500), nullable=True)
    category = Column(Enum(VulnerabilityCategory), default=VulnerabilityCategory.UNKNOWN)
    technology = Column(String(255), nullable=True)        # Spring, Log4j, Struts2
    framework = Column(String(255), nullable=True)
    version_affected = Column(String(255), nullable=True)
    description = Column(Text, nullable=True)
    remediation = Column(Text, nullable=True)
    reference_url = Column(String(1000), nullable=True)
    cve_id = Column(String(50), nullable=True)

    # Ingestion metadata
    content_hash = Column(String(64), nullable=True, index=True)  # SHA-256 for dedup
    ingestion_time = Column(DateTime(timezone=True), server_default=func.now())
    dataset_version = Column(String(100), nullable=True)

    chunks = relationship("KnowledgeChunk", back_populates="document", cascade="all, delete-orphan")

    __table_args__ = (
        Index("ix_knowledge_documents_source", "source"),
        Index("ix_knowledge_documents_technology", "technology"),
    )


class KnowledgeChunk(Base):
    """
    A text chunk from a knowledge document, with its vector stored in FAISS.
    Paper: "text chunking technology to disassemble each vulnerability example into independent text units"
    """
    __tablename__ = "knowledge_chunks"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    document_id = Column(String(36), ForeignKey("knowledge_documents.id"), nullable=False)

    # Text content
    chunk_text = Column(Text, nullable=False)
    chunk_position = Column(Integer, nullable=False)    # Position in parent document
    chunk_size = Column(Integer, nullable=True)         # Token count

    # FAISS mapping — CRITICAL for traceability
    # faiss_index_id maps to the row in the FAISS index
    faiss_index_id = Column(Integer, nullable=True, index=True)
    faiss_index_version = Column(String(100), nullable=True)
    embedding_model = Column(String(255), nullable=True)

    metadata_ = Column("metadata", JSON, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    document = relationship("KnowledgeDocument", back_populates="chunks")

    __table_args__ = (
        Index("ix_knowledge_chunks_faiss_id", "faiss_index_id"),
        Index("ix_knowledge_chunks_document", "document_id"),
    )



class Retrieval(Base):
    """
    Records one RAG retrieval operation — CRITICAL for auditability.
    Paper: the system must be traceable.
    """
    __tablename__ = "retrievals"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False)
    fingerprint_id = Column(String(36), ForeignKey("fingerprints.id"), nullable=False)

    # Query information
    query_text = Column(Text, nullable=False)
    query_embedding_model = Column(String(255), nullable=False)
    query_embedding_model_version = Column(String(100), nullable=True)

    # Retrieval parameters
    faiss_index_version = Column(String(100), nullable=True)
    top_k = Column(Integer, nullable=False)
    similarity_threshold = Column(Float, nullable=False)  # Paper: 0.6

    # Results
    results = Column(JSON, nullable=False)          # List of {chunk_id, score, text, source}
    max_similarity = Column(Float, nullable=True)   # Highest similarity found
    threshold_passed = Column(Boolean, nullable=False)  # True if max_sim >= threshold

    # Selected evidence for LLM
    selected_chunk_ids = Column(JSON, nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now())

    scan = relationship("Scan", back_populates="retrievals")
    fingerprint = relationship("Fingerprint", back_populates="retrievals")


class Analysis(Base):
    """
    LLM analysis result.
    Paper: LLM output includes vulnerability analysis, severity, remediation.
    """
    __tablename__ = "analyses"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False)
    retrieval_id = Column(String(36), ForeignKey("retrievals.id"), nullable=True)

    # LLM configuration used
    llm_provider = Column(String(100), nullable=False)
    llm_model = Column(String(255), nullable=False)
    prompt_version = Column(String(50), nullable=False)

    # Input/Output
    prompt_text = Column(Text, nullable=False)          # Full prompt sent to LLM
    raw_llm_response = Column(Text, nullable=False)     # Raw LLM response (for audit)

    # Parsed output (from paper's described output)
    potential_vulnerability = Column(Text, nullable=True)
    category = Column(Enum(VulnerabilityCategory), default=VulnerabilityCategory.UNKNOWN)
    affected_technology = Column(String(500), nullable=True)
    evidence_summary = Column(JSON, nullable=True)
    analysis_text = Column(Text, nullable=True)
    severity = Column(Enum(SeverityLevel), nullable=True)
    remediation_steps = Column(JSON, nullable=True)
    uncertainty_statement = Column(Text, nullable=True)
    validation_required = Column(Boolean, default=True)

    # Always INFERRED — never auto-confirmed
    evidence_type = Column(Enum(EvidenceType), default=EvidenceType.INFERRED)

    created_at = Column(DateTime(timezone=True), server_default=func.now())

    scan = relationship("Scan", back_populates="analyses")
    findings = relationship("Finding", back_populates="analysis", cascade="all, delete-orphan")


class Finding(Base):
    """
    A potential vulnerability finding requiring human validation.
    Paper: system operates as human-in-the-loop assistant.
    """
    __tablename__ = "findings"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False)
    analysis_id = Column(String(36), ForeignKey("analyses.id"), nullable=False)

    # Finding details
    title = Column(String(500), nullable=False)
    category = Column(Enum(VulnerabilityCategory), default=VulnerabilityCategory.UNKNOWN)
    severity = Column(Enum(SeverityLevel), nullable=True)
    description = Column(Text, nullable=True)
    affected_components = Column(JSON, nullable=True)
    remediation = Column(JSON, nullable=True)

    # Human validation status — starts as POTENTIAL
    status = Column(Enum(FindingStatus), default=FindingStatus.POTENTIAL, nullable=False, index=True)
    evidence_type = Column(Enum(EvidenceType), default=EvidenceType.INFERRED)

    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())

    scan = relationship("Scan", back_populates="findings")
    analysis = relationship("Analysis", back_populates="findings")
    validations = relationship("Validation", back_populates="finding", cascade="all, delete-orphan")

    __table_args__ = (
        Index("ix_findings_scan_status", "scan_id", "status"),
    )


class Validation(Base):
    """
    Human validation record for a finding.
    Paper: "human-in-the-loop assistant"
    """
    __tablename__ = "validations"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    finding_id = Column(String(36), ForeignKey("findings.id"), nullable=False)

    # Reviewer information
    reviewer = Column(String(255), nullable=False)
    review_timestamp = Column(DateTime(timezone=True), server_default=func.now())

    # Status transition
    old_status = Column(Enum(FindingStatus), nullable=False)
    new_status = Column(Enum(FindingStatus), nullable=False)
    comment = Column(Text, nullable=True)

    # Additional evidence requested
    additional_evidence_requested = Column(Text, nullable=True)

    finding = relationship("Finding", back_populates="validations")


class Report(Base):
    """Generated security report."""
    __tablename__ = "reports"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False)

    title = Column(String(500), nullable=False)
    format = Column(String(50), default="json")  # json | markdown | html
    content = Column(Text, nullable=False)
    file_path = Column(String(1000), nullable=True)

    # Summary statistics
    total_findings = Column(Integer, default=0)
    validated_findings = Column(Integer, default=0)
    rejected_findings = Column(Integer, default=0)
    pending_findings = Column(Integer, default=0)

    created_at = Column(DateTime(timezone=True), server_default=func.now())

    scan = relationship("Scan", back_populates="reports")


class AuditEvent(Base):
    """
    Immutable audit log for all system events.
    Paper: "the entire analytical chain is clear and transparent."
    """
    __tablename__ = "audit_events"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    event_type = Column(String(100), nullable=False, index=True)
    entity_type = Column(String(100), nullable=True)    # scan, finding, validation, etc.
    entity_id = Column(String(36), nullable=True, index=True)
    actor = Column(String(255), nullable=True)
    description = Column(Text, nullable=True)
    data = Column(JSON, nullable=True)
    timestamp = Column(DateTime(timezone=True), server_default=func.now(), index=True)

    __table_args__ = (
        Index("ix_audit_events_timestamp", "timestamp"),
    )


class User(Base):
    """
    User account model for administrative authentication.
    """
    __tablename__ = "users"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    email = Column(String(255), unique=True, nullable=False, index=True)
    hashed_password = Column(String(255), nullable=False)
    role = Column(String(50), default="admin", nullable=False)
    is_active = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

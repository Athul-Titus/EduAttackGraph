"""
SQLAlchemy Database Models for LLM-EduAttackGraph

Tables:
- targets
- scans
- ports
- services
- fingerprints
- knowledge_documents
- knowledge_chunks
- retrievals
- analyses
- findings
- validations
- reports
- audit_events

FAISS index is stored separately from this relational database.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum as PyEnum
from typing import Optional, List

from sqlalchemy import (
    Column, String, Integer, Float, Boolean, DateTime, Text, JSON,
    ForeignKey, Enum, Index, UniqueConstraint
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

Base = declarative_base()


def generate_uuid() -> str:
    return str(uuid.uuid4())


# ==============================================================================
# Enums
# ==============================================================================

class ScanStatus(str, PyEnum):
    PENDING = "pending"
    RUNNING = "running"
    FINGERPRINTING = "fingerprinting"
    ANALYZING = "analyzing"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class PortState(str, PyEnum):
    OPEN = "open"
    CLOSED = "closed"
    FILTERED = "filtered"


class VulnerabilityCategory(str, PyEnum):
    """Six categories from the paper."""
    O1_RCE = "O1_RCE"                           # Remote Code/Command Execution
    O2_SQL_INJECTION = "O2_SQL_INJECTION"        # SQL Injection
    O3_WEAK_PASSWORD = "O3_WEAK_PASSWORD"        # Weak Password
    O4_UNAUTHORIZED = "O4_UNAUTHORIZED"          # Unauthorized Access
    O5_TOKEN_TAMPERING = "O5_TOKEN_TAMPERING"    # Token Tampering
    O6_INFO_DISCLOSURE = "O6_INFO_DISCLOSURE"    # Sensitive Information Disclosure
    UNKNOWN = "UNKNOWN"


class SeverityLevel(str, PyEnum):
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFORMATIONAL = "informational"


class FindingStatus(str, PyEnum):
    """
    Human-in-the-loop workflow states.
    LLM output starts as POTENTIAL, never auto-confirmed.
    """
    POTENTIAL = "potential"           # LLM inferred this — NOT confirmed
    PENDING_REVIEW = "pending_review" # Queued for human review
    VALIDATED = "validated"           # Human accepted as a real finding
    REJECTED = "rejected"             # Human rejected (false positive)
    NEEDS_MORE_EVIDENCE = "needs_more_evidence"  # Human needs more info


class EvidenceType(str, PyEnum):
    """
    Evidence classification — critical for transparency.
    """
    OBSERVED = "observed"     # Directly obtained from reconnaissance
    RETRIEVED = "retrieved"   # From RAG knowledge base (Awesome-POC)
    INFERRED = "inferred"     # Generated by LLM (not confirmed)
    VALIDATED = "validated"   # Accepted by human analyst


# ==============================================================================
# Models
# ==============================================================================

class Target(Base):
    """
    Authorized target registry.
    Only targets registered here can be scanned.
    """
    __tablename__ = "targets"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    hostname = Column(String(255), nullable=False, index=True)
    ip_address = Column(String(45), nullable=True)  # IPv4 or IPv6
    description = Column(Text, nullable=True)
    authorized = Column(Boolean, default=True, nullable=False)
    authorization_note = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())

    scans = relationship("Scan", back_populates="target", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<Target hostname={self.hostname} authorized={self.authorized}>"


class Scan(Base):
    """
    Represents one complete scan session: fingerprint → RAG → LLM → validation.
    """
    __tablename__ = "scans"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    target_id = Column(String(36), ForeignKey("targets.id"), nullable=False)
    status = Column(Enum(ScanStatus), default=ScanStatus.PENDING, nullable=False, index=True)
    initiated_by = Column(String(255), nullable=True)  # user/system identifier
    notes = Column(Text, nullable=True)

    # Timing
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)

    # Configuration snapshot (at time of scan)
    embedding_model = Column(String(255), nullable=True)
    embedding_model_version = Column(String(100), nullable=True)
    faiss_index_version = Column(String(100), nullable=True)
    similarity_threshold = Column(Float, nullable=True)
    top_k = Column(Integer, nullable=True)
    llm_provider = Column(String(100), nullable=True)
    llm_model = Column(String(255), nullable=True)
    prompt_version = Column(String(50), nullable=True)

    error_message = Column(Text, nullable=True)

    # Relationships
    target = relationship("Target", back_populates="scans")
    ports = relationship("Port", back_populates="scan", cascade="all, delete-orphan")
    fingerprint = relationship("Fingerprint", back_populates="scan", uselist=False, cascade="all, delete-orphan")
    retrievals = relationship("Retrieval", back_populates="scan", cascade="all, delete-orphan")
    analyses = relationship("Analysis", back_populates="scan", cascade="all, delete-orphan")
    findings = relationship("Finding", back_populates="scan", cascade="all, delete-orphan")
    reports = relationship("Report", back_populates="scan", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<Scan id={self.id} status={self.status}>"


class Port(Base):
    """Open port discovered during fingerprinting."""
    __tablename__ = "ports"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False)
    port_number = Column(Integer, nullable=False)
    protocol = Column(String(10), default="tcp")
    state = Column(Enum(PortState), default=PortState.OPEN)
    evidence_type = Column(Enum(EvidenceType), default=EvidenceType.OBSERVED)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    scan = relationship("Scan", back_populates="ports")
    service = relationship("Service", back_populates="port", uselist=False, cascade="all, delete-orphan")

    __table_args__ = (
        Index("ix_ports_scan_port", "scan_id", "port_number"),
    )


class Service(Base):
    """Service identified on an open port."""
    __tablename__ = "services"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    port_id = Column(String(36), ForeignKey("ports.id"), nullable=False)
    name = Column(String(100), nullable=True)      # http, https, ftp, ssh, mysql, etc.
    version = Column(String(255), nullable=True)   # Apache/2.4.41, nginx/1.18.0
    product = Column(String(255), nullable=True)
    banner = Column(Text, nullable=True)
    evidence = Column(JSON, nullable=True)          # Raw detection evidence
    evidence_type = Column(Enum(EvidenceType), default=EvidenceType.OBSERVED)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    port = relationship("Port", back_populates="service")


class Fingerprint(Base):
    """
    Structured fingerprint produced by the fingerprinting engine.
    This is the output of Stage 1 (Algorithm 1 in the paper).
    The fingerprint text representation becomes the query for Stage 2 RAG.
    """
    __tablename__ = "fingerprints"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    scan_id = Column(String(36), ForeignKey("scans.id"), nullable=False, unique=True)

    # Raw structured data
    target_hostname = Column(String(255), nullable=False)
    raw_data = Column(JSON, nullable=False)         # Full fingerprint JSON

    # Extracted fields (from Algorithm 1 service_map)
    web_framework = Column(String(255), nullable=True)      # RuoYi, Spring, Django, etc.
    web_application = Column(String(255), nullable=True)
    server_software = Column(String(255), nullable=True)    # Apache, nginx, IIS
    server_version = Column(String(100), nullable=True)
    technologies = Column(JSON, nullable=True)              # List of detected technologies
    cms = Column(String(255), nullable=True)

    # Text representation (fed to embedding model as the query)
    text_representation = Column(Text, nullable=True)

    # Spark API pre-analysis (optional, from Algorithm 1)
    spark_analysis = Column(JSON, nullable=True)

    evidence_type = Column(Enum(EvidenceType), default=EvidenceType.OBSERVED)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    scan = relationship("Scan", back_populates="fingerprint")
    retrievals = relationship("Retrieval", back_populates="fingerprint", cascade="all, delete-orphan")


